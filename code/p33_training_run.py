ACC_RATIO = float(committed("p21.tex", "p21.acc.ratio") or 1.83)
emit("p33.fail.acc", ACC_RATIO, 2)

# The count the assembly is for.
SILENT, LOUD = 4, 2
assert SILENT + LOUD == 6
