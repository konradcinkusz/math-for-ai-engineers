"""P33 --- Anatomy of a training run.

Every number Program P33 prints, and the assertions that keep them honest.

PART IX'S CONTRACT IS THAT IT INTRODUCES NO NEW MATHEMATICS, so the first
question was P32's: not "what is left of the subject" but "which lines of the
brief have already been delivered".  `grep -rn 'prog:P33' programs/en/*.tex`
answers it, and the answer is unusually clean -- only F03 defers here, twice,
and both deferrals are exactly the two halves the brief calls this program's
own:

  F03  "Program P33 reads a loss curve as evidence -- what a plateau, a spike
       and a suspiciously smooth descent each imply, and which of them are
       distinguishable from noise."  It owns the log axis and stops there.
  F03  "Program P33 treats such a fit as an empirical fit with a stated
       extrapolation error rather than as a law of nature."  It owns "a power
       law is a straight line on log-log axes and the gradient is the
       exponent" and never fits one.

The SIX bracketed items in the brief are spent by construction, each by a
program whose own header says so:

  P26 the loss as maximum likelihood      P18 its gradient as p - y
  P20 the optimiser (F04 owns the average and the bias correction)
  P01 precision, and P20 loss scaling     P17 eta < 2/lambda_max
  F06 clipping outright, P21 the noise model behind it

So this program re-teaches none of them.  It assembles them, and then asks the
one question the assembly makes available and no owner could: OF THE SIX,
WHICH FAIL SILENTLY?  Four do, and all four show up on the loss curve -- which
is what makes section 2 a reading of evidence rather than a gallery of shapes.

METHOD, from P30, P31 and P32: derive in closed form wherever possible,
because a demonstration whose answer depends on a seed measures the sampler.
NOTHING HERE IS SAMPLED.  The plateau, the spike and the smoother are all
exact statements about a normal distribution, computed with math.erf; the
scaling fit is least squares in closed form over data generated from a
relation whose truth is known because this script chose it.

And issue #47 requires that any loss curve shown be generated by a script
rather than drawn.  It is -- and generating it needs NO trained model, which
is P32's split asked of this program's own claims: the shapes are properties
of an optimiser walking a quadratic under minibatch noise, and the book owns
the optimiser (P20), the quadratic (P17, P10) and the noise (P21).

Run:  python3 code/p33_training_run.py
"""

from __future__ import annotations

import math
import re
from fractions import Fraction
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "figures" / "values" / "p33.tex"
TRANSCRIPT = OUT.parent.parent / "transcripts"
VALUES: dict[str, tuple[str, bool]] = {}


def emit(key: str, value, digits: int | None = None) -> None:
    if isinstance(value, float) and digits is not None:
        body = f"{value:.{digits}f}"
    elif isinstance(value, float):
        body = repr(value)
    else:
        body = str(value)
    try:
        numeric = math.isfinite(float(body.replace("e", "E")))
    except ValueError:
        numeric = False
    VALUES[key] = (body, numeric)


def committed(fname: str, key: str) -> str | None:
    """Another program's committed value, read back so the two cannot drift."""
    path = OUT.parent / fname
    if not path.exists():                                    # pragma: no cover
        return None
    m = re.search(r"\\mfaval\{" + re.escape(key) + r"\}\{([^}]*)\}",
                  path.read_text(encoding="utf8"))
    return m.group(1) if m else None


def pct(x: float) -> float:
    """Refuse a percentage that rounds to 0 or 100 and so reads as exact."""
    r = round(x, 1)
    assert r not in (0.0, 100.0), (
        f"{x} rounds to {r} per cent, which reads as exact and is not.")
    return x


def reproduces(value: float, digits: int, *operands, op) -> float:
    """Refuse a quantity that does not come back out of its own printed page."""
    shown = [float(f"{v:.{d}f}") for v, d in operands]
    assert f"{op(*shown):.{digits}f}" == f"{value:.{digits}f}", (
        f"the page prints {value:.{digits}f} beside operands that give "
        f"{op(*shown):.{digits}f}; a reader who checks will find it wrong.")
    return value


def Phi(z: float) -> float:
    """The standard normal distribution function, from the error function."""
    return 0.5 * (1.0 + math.erf(z / math.sqrt(2.0)))


def z_for(tail: float) -> float:
    """The z with an upper tail of `tail`, by bisection.  No library needed."""
    lo, hi = 0.0, 40.0
    for _ in range(200):
        mid = (lo + hi) / 2.0
        if 1.0 - Phi(mid) > tail:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2.0


assert abs(Phi(0.0) - 0.5) < 1e-15
assert abs(z_for(0.025) - 1.959964) < 1e-5, z_for(0.025)


