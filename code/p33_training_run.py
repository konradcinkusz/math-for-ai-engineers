#
# The one thing the assembly ADDS is the question no owner could ask: put the
# six in the order they execute and ask which of them, got wrong, raises
# nothing.  Four do not raise, and all four move the loss curve -- which is
# what makes section 2 a reading of evidence rather than a gallery of shapes.
# ======================================================================

# --- the loss (P26, over F02's own committed figure) ---
LOSS_NATS = float(committed("p26.tex", "p26.f02.loss") or 2.4)
emit("p33.loss.nats", LOSS_NATS, 1)

# Its silent failure is P19's: average the per-sequence perplexities instead of
# exponentiating the average loss, and at a per-token spread of 2 the reported
# figure is this many times the true one.  No error, no warning.
PPL_RATIO = float(committed("p19.tex", "p19.ppl.ratio.20") or 7.42)
emit("p33.fail.ppl", PPL_RATIO, 2)

# --- the gradient (P18) ---
# Its failure is LOUD, and that is the point of the contrast: the honest
# two-step route forms -1/p_c, and once a logit falls this far below the
# largest, p_c underflows and it divides by zero.
GRAD_CLIFF = float(committed("p18.tex", "p18.cliff") or -744)
emit("p33.grad.cliff", GRAD_CLIFF, 0)

# --- the optimiser (P20; F04 owns the average) ---
# Its silent failure is the convention F04 measured: carry a step size across
# the two forms of momentum and the walk takes this many times as long, or
# diverges.  P20 committed the walk that reproduces exactly when rescaled.
CONV_SAME = int(float(committed("p20.tex", "p20.conv.same") or 67))
CONV_FOLD = int(float(committed("p20.tex", "p20.fold") or 10))
emit("p33.conv.same", CONV_SAME)
emit("p33.conv.fold", CONV_FOLD)

# --- precision (P01) ---
# Its silent failure is swamping: under round-to-nearest a contribution below
# half the gap at the running total moves NOTHING, and in bf16 that threshold
# is this fraction of the total.
SWAMP_BF16_PCT = float(committed("p01.tex", "p01.swamp.bf16.pct") or 0.39)
emit("p33.fail.swamp", SWAMP_BF16_PCT, 2)

# --- the schedule and the bound (P17) ---
# LOUD.  Above 2/lambda_max every eigendirection with lambda above the
# threshold grows, and the run does not merely get worse -- it leaves.
LAM_HI = float(committed("p17.tex", "p17.lam.hi") or 20)
LAM_LO = float(committed("p17.tex", "p17.lam.lo") or 1)

# GATE.  P17's committed boundary is 2/lambda_max, and recomputing it here is
# what makes the hand-over real rather than a quotation.  Note what this
# assertion caught on its first run: an earlier draft wrote it as
# `eta_star < 2/lambda_max`, which is the SAME QUANTITY compared with itself
# -- P17's `eta.star` IS the boundary, not the optimum -- and the two print
# identically at two decimals, so nothing but the assertion would have said so.
ETA_BOUND = 2.0 / LAM_HI
_p17_bound = float(committed("p17.tex", "p17.eta.star") or 0.10)
assert abs(ETA_BOUND - _p17_bound) < 5e-3, (ETA_BOUND, _p17_bound)
emit("p33.eta.bound", ETA_BOUND, 2)

# The optimum for plain descent on this bowl is 2/(lambda_hi + lambda_lo), and
# P17 and P20 both committed it.  THE ASSEMBLY'S NUMBER IS THE GAP BETWEEN
# THEM: the step size a schedule wants and the step size that ends the run
# differ by this much, and a schedule spends its whole life inside that band.
# Computed here and GATED against the two programs that committed it, rather
# than read back and reused: reading it back would round it to three decimals
# first, and the margin below is exactly the check that a rounded operand
# breaks.  P05's rule -- a comparison against a value that has already lost
# the digits you are about to test is not a comparison.
ETA_BEST = 2.0 / (LAM_HI + LAM_LO)
for _f, _k in (("p17.tex", "p17.best.eta"), ("p20.tex", "p20.eta.best")):
    _c = committed(_f, _k)
    assert _c is not None and f"{ETA_BEST:.3f}" == _c, (_k, _c, ETA_BEST)
emit("p33.eta.best", ETA_BEST, 3)

# Reported at zero decimals BECAUSE that is the only precision at which the
# exact margin and the margin a reader computes from the two printed figures
# agree -- 4.76 against 5.00 at two.  F05's rule, applied before it bit.
ETA_MARGIN_PCT = reproduces(
    100.0 * (ETA_BOUND - ETA_BEST) / ETA_BOUND, 0,
    (ETA_BOUND, 2), (ETA_BEST, 3),
    op=lambda b, e: 100.0 * (b - e) / b)
emit("p33.eta.margin", ETA_MARGIN_PCT, 0)

# --- clipping and minibatch noise (F06 and P21) ---
# Silent, twice over: accumulation divides by the wrong denominator and the
